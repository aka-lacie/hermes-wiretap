"""Build the self-contained Desktop entry from the canonical dashboard renderer.

No npm/bundler dependency. The stock Desktop loader permits only SDK/react imports,
so the renderer factory and scoped stylesheet are bundled as static source, not
fetched/evaluated or loaded through an iframe. --check is suitable for CI.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
START = '  // BEGIN SHARED WIRETAP RENDERER'
END = '  // END SHARED WIRETAP RENDERER'


def build():
    dashboard = (ROOT / 'dashboard/dist/index.js').read_text(encoding='utf-8')
    shared = dashboard.split(START, 1)[1].split('\n', 1)[1].split(END, 1)[0]
    template = (HERE / 'entry.js').read_text(encoding='utf-8')
    css = (ROOT / 'dashboard/dist/style.css').read_text(encoding='utf-8')
    css += '\n' + (HERE / 'desktop-theme.css').read_text(encoding='utf-8')
    return ('// Generated by desktop/build.py. Edit desktop/entry.js or the dashboard renderer, then rebuild.\n'
            + template.replace('/* SHARED_RENDERER */', shared.rstrip())
            .replace("/* SHARED_STYLES */ ''", json.dumps(css, ensure_ascii=False)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = build()
    target = HERE / 'plugin.js'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            parser.exit(1, 'Desktop bundle is stale; run python3 desktop/build.py\n')
    else:
        target.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
